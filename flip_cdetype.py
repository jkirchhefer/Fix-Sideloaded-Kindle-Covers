#!/usr/bin/env python3
"""
flip_cdetype.py - mark Kindle AZW3/MOBI files as personal documents (PDOC).

Newer Kindles (2026 models) won't let anything write cover thumbnails to
system/thumbnails, so sideloaded books tagged as store books (EBOK) show a
blank cover. Books tagged as personal documents (PDOC) get their cover
generated by the Kindle itself from the image embedded in the file.

This script changes ONLY that tag (the "cdetype" field, EXTH record 501).
Text, styling, images and every other byte of the book are copied as-is.
Originals are never modified; changed copies are written to a new folder.

Usage:
    python3 flip_cdetype.py ~/Downloads/standard-ebooks
    python3 flip_cdetype.py book1.azw3 book2.azw3 -o ~/Desktop/kindle-ready
    python3 flip_cdetype.py some-folder --type EBOK     # undo (back to EBOK)
    python3 flip_cdetype.py some-folder --check         # just report tags

By default, output goes to a "pdoc" folder next to the inputs.
"""
import argparse
import struct
import sys
from pathlib import Path

PDB_HEADER_LEN = 78
EXTH_PRESENT_FLAG = 0x40
CDETYPE = 501        # EXTH record holding EBOK / PDOC / EBSP
KF8_BOUNDARY = 121   # EXTH record pointing at the KF8 header in joint MOBI/KF8 files
FULL_NAME_OFFSET_POS = 0x54  # byte offset (within record 0) of the full-name pointer
EXTENSIONS = {".azw3", ".azw", ".mobi"}


class NotKindleFile(Exception):
    pass


# ---------------------------------------------------------------- PDB layer

def split_records(data):
    if len(data) < PDB_HEADER_LEN or data[60:68] != b"BOOKMOBI":
        raise NotKindleFile("not a Kindle (BOOKMOBI) file")
    n = struct.unpack_from(">H", data, 76)[0]
    table_end = PDB_HEADER_LEN + n * 8
    offsets = [struct.unpack_from(">I", data, PDB_HEADER_LEN + i * 8)[0] for i in range(n)]
    attrs = [data[PDB_HEADER_LEN + i * 8 + 4:PDB_HEADER_LEN + i * 8 + 8] for i in range(n)]
    gap = data[table_end:offsets[0]]  # usually two zero bytes
    bounds = offsets + [len(data)]
    records = [bytearray(data[bounds[i]:bounds[i + 1]]) for i in range(n)]
    return records, attrs, gap


def join_records(data, records, attrs, gap):
    n = len(records)
    out = bytearray(data[:PDB_HEADER_LEN])
    pos = PDB_HEADER_LEN + n * 8 + len(gap)
    for rec, attr in zip(records, attrs):
        out += struct.pack(">I", pos) + attr
        pos += len(rec)
    out += gap
    for rec in records:
        out += rec
    return bytes(out)


# --------------------------------------------------------------- EXTH layer

def read_exth(rec):
    """Return (start, length, items) for the EXTH block of a MOBI/KF8 header record, or None."""
    if rec[16:20] != b"MOBI":
        raise NotKindleFile("missing MOBI header")
    mobi_len = struct.unpack_from(">I", rec, 20)[0]
    flags = struct.unpack_from(">I", rec, 0x80)[0]
    if not flags & EXTH_PRESENT_FLAG:
        return None
    start = 16 + mobi_len
    if rec[start:start + 4] != b"EXTH":
        raise NotKindleFile("EXTH flag set but EXTH block missing")
    length, count = struct.unpack_from(">II", rec, start + 4)
    items, p = [], start + 12
    for _ in range(count):
        rtype, rlen = struct.unpack_from(">II", rec, p)
        items.append([rtype, bytes(rec[p + 8:p + rlen])])
        p += rlen
    return start, length, items


def get_cdetype(rec):
    exth = read_exth(rec)
    if not exth:
        return None
    for rtype, value in exth[2]:
        if rtype == CDETYPE:
            return value.decode("ascii", "replace")
    return None


def set_cdetype(rec, new_type):
    """Set EXTH 501 in a header record. Returns the (possibly new) record."""
    exth = read_exth(rec)
    if exth is None:
        raise NotKindleFile("file has no EXTH metadata block")
    start, length, items = exth
    value = new_type.encode("ascii")

    # Fast path: an existing 4-byte value is overwritten in place, so no
    # length or offset anywhere in the file changes.
    p = start + 12
    for rtype, old in items:
        rlen = 8 + len(old)
        if rtype == CDETYPE and len(old) == len(value):
            rec[p + 8:p + 8 + len(value)] = value
            return rec
        p += rlen

    # Slow path: record missing (or odd length) -> rebuild the EXTH block.
    items = [it for it in items if it[0] != CDETYPE] + [[CDETYPE, value]]
    body = b"".join(struct.pack(">II", t, 8 + len(v)) + v for t, v in items)
    new_len = 12 + len(body)
    pad = b"\0" * (4 - new_len % 4)  # same 1-4 byte padding calibre/kindlegen use
    new_block = b"EXTH" + struct.pack(">II", new_len, len(items)) + body + pad

    old_end = start + length
    while old_end < len(rec) and old_end < start + length + 4 and rec[old_end] == 0:
        old_end += 1  # skip the old padding
    delta = len(new_block) - (old_end - start)

    full_name_off = struct.unpack_from(">I", rec, FULL_NAME_OFFSET_POS)[0]
    new_rec = rec[:start] + new_block + rec[old_end:]
    if full_name_off >= start:
        struct.pack_into(">I", new_rec, FULL_NAME_OFFSET_POS, full_name_off + delta)
    return new_rec


def header_indices(records):
    """Record 0, plus the KF8 header record in joint MOBI/KF8 files."""
    idx = [0]
    exth = read_exth(records[0])
    if exth:
        for rtype, value in exth[2]:
            if rtype == KF8_BOUNDARY and len(value) == 4:
                k = struct.unpack(">I", value)[0]
                if 0 < k < len(records) and records[k][16:20] == b"MOBI":
                    idx.append(k)
    return idx


# ------------------------------------------------------------------- driver

def process(path, out_dir, new_type, check_only):
    data = path.read_bytes()
    records, attrs, gap = split_records(data)
    heads = header_indices(records)
    before = [get_cdetype(records[i]) or "none" for i in heads]

    if check_only:
        return "/".join(before)
    if all(t == new_type for t in before):
        result, status = data, f"already {new_type}"
    else:
        for i in heads:
            records[i] = set_cdetype(records[i], new_type)
        result = join_records(data, records, attrs, gap)
        # Verify by re-reading what we just built.
        r2, _, _ = split_records(result)
        after = [get_cdetype(r2[i]) for i in header_indices(r2)]
        if any(t != new_type for t in after):
            raise NotKindleFile("verification failed; file not written")
        status = f"{'/'.join(before)} -> {new_type}"

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / path.name).write_bytes(result)
    return status


def gather(inputs, out_override):
    jobs = []
    for raw in inputs:
        p = Path(raw).expanduser()
        if p.is_dir():
            out = Path(out_override).expanduser() if out_override else p / "pdoc"
            for f in sorted(p.iterdir()):
                if f.is_file() and f.suffix.lower() in EXTENSIONS:
                    jobs.append((f, out))
        elif p.is_file():
            out = Path(out_override).expanduser() if out_override else p.parent / "pdoc"
            jobs.append((p, out))
        else:
            print(f"skip: {raw} (not found)", file=sys.stderr)
    return jobs


def main():
    ap = argparse.ArgumentParser(description="Set the Kindle cdetype (EBOK/PDOC) on AZW3/MOBI files.")
    ap.add_argument("paths", nargs="+", help="files or folders of .azw3/.azw/.mobi books")
    ap.add_argument("-o", "--output", help="output folder (default: 'pdoc' next to the inputs)")
    ap.add_argument("--type", default="PDOC", choices=["PDOC", "EBOK"], help="tag to set (default PDOC)")
    ap.add_argument("--check", action="store_true", help="only print each file's current tag")
    args = ap.parse_args()

    jobs = gather(args.paths, args.output)
    if not jobs:
        sys.exit("No .azw3/.azw/.mobi files found.")

    ok = failed = 0
    for path, out in jobs:
        try:
            status = process(path, out, args.type, args.check)
            print(f"{status:<16} {path.name}")
            ok += 1
        except (NotKindleFile, struct.error) as e:
            print(f"{'FAILED':<16} {path.name}: {e}", file=sys.stderr)
            failed += 1

    if not args.check:
        outs = sorted({str(o) for _, o in jobs})
        print(f"\n{ok} written, {failed} failed. Output: {', '.join(outs)}")


if __name__ == "__main__":
    main()
